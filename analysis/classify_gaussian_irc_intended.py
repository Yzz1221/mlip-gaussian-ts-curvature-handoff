EXPECTED_REACTBENCH_TABLE_GENERATOR_SHA256 = "3cf210b3b3b898b123d4e1c27fe02c2c066d52dafbca1acba504297e2ca5031d"
IGNORE_ELEMENTS = frozenset({"zn", "mg", "li", "si", "ag", "cu", "b"})
POINT_RE = re.compile(
    r"Point\s+Number\s+(\d+)\s+in\s+(FORWARD|REVERSE)\s+path\s+direction\.",
    re.IGNORECASE,
)

# Index is atomic number.  Only reference-element validation uses this table;
