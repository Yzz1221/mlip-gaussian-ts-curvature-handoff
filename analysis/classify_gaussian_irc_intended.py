#!/usr/bin/env python3
"""Classify Gaussian IRC endpoints with the ReactBench Intended criterion.

The two IRC endpoints are read directly from ``irc.log``.  The expected
reactant and product must be supplied as a two-frame XYZ in ReactBench order.
Connectivity is generated by ReactBench's own ``table_generator`` so its
distance/radius, H-H, and maximum-valence behavior stays authoritative.
"""

from __future__ import annotations

